-- Place in StarterPlayer > StarterPlayerScripts. Put DulcanUI ModuleScript in ReplicatedStorage.
local UI = require(game:GetService("ReplicatedStorage"):WaitForChild("DulcanUI"))
local window = UI:CreateWindow({Title="DULCAN UI", Version="0.1.0", Theme="Purple", StatusBar=true, Transparency=.18})
local settings = window:CreateTab({Title="Settings", Columns=2})
local performance = settings:CreateSection("Performance",1)
performance:AddParagraph({Content="Live FPS and network latency are shown in the status bar."})
performance:AddToggle({Title="Show status bar", Id="status", Default=true, Callback=function(v) window.StatusBar.Visible=v end})
performance:AddButton({Title="Test notification",Callback=function() window:Notify({Title="Dulcan UI",Content="Notification received.",Duration=4}) end})
local interface = settings:CreateSection("Interface",2)
interface:AddDropdown({Title="Theme",Id="theme",Options={"Purple","Red","Blue","Green","Gold","Midnight"},Default="Purple",Callback=function(v) window:SetTheme(v) end})
interface:AddSlider({Title="Transparency",Id="opacity",Min=0,Max=80,Default=18,Callback=function(v) window:SetTransparency(v/100) end})
interface:AddKeybind({Title="Toggle key",Id="key",Default="RightShift",Callback=function(k) window:SetToggleKey(k) end})
local demo=window:CreateTab("Components"):CreateSection("Examples")
demo:AddInput({Title="Profile name",Id="profile",Placeholder="Enter name",Callback=function(v) print(v) end})
demo:AddDivider()
demo:AddButton({Title="Print configuration JSON",Callback=function() print(window:ExportConfig()) end})
window:Notify({Title="DULCAN UI",Content="Framework loaded."})
